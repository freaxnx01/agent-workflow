#!/usr/bin/env bash
#
# publish-knowledge-bundle.sh — land a regenerated knowledge bundle on main
# through an App-authored PR with squash auto-merge (#601).
#
# Commits the bundle onto $BRANCH, force-pushes it, opens the PR (or reuses the
# open one) and enables auto-merge. Extracted from
# .github/workflows/knowledge-bundle.yml: as inline YAML this logic was neither
# linted nor executed by any test, only grepped for.
#
# Run from the agent-workflow checkout, after scripts/build-knowledge-bundle.sh
# has regenerated the bundle in the worktree. `origin` must be the repo to push
# to; the branch is force-pushed because it holds generated output only.
#
# `[skip ci]` goes ONLY on the squash-merge subject: on the PR head commit the
# required checks would be skipped and the merge would stall. On the merge
# commit it stops the pipelines on main.
#
# Required env: BRANCH, SUBJECT, GH_TOKEN (also read by `gh`).
# Optional env: GH_REPO (gh's own), BUNDLE_PATH.
# Exit codes: 0 ok; 2 required env missing.
set -euo pipefail
IFS=$'\n\t'

BUNDLE_PATH="${BUNDLE_PATH:-docs/generated/software-factory-knowledge.md}"

require_env() {  # <name>...
  local name
  for name in "$@"; do
    [[ -n "${!name:-}" ]] && continue
    printf 'error: %s must be set\n' "$name" >&2
    exit 2
  done
}

commit_bundle() {
  git switch -C "$BRANCH"
  git add "$BUNDLE_PATH"
  # The runner checkout has no committer identity, and the bundle is the
  # pipeline's output rather than any person's change.
  git -c user.name='github-actions[bot]' \
      -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
      commit -q -m "$SUBJECT" -m "Generated by scripts/build-knowledge-bundle.sh (#601)."
}

push_branch() {
  # `gh auth setup-git` installs gh as git's credential helper, so GH_TOKEN
  # never reaches the remote URL or this process's argv the way an
  # https://x-access-token:<token>@github.com/... push target would.
  gh auth setup-git
  git push --force origin "HEAD:refs/heads/${BRANCH}"
}

# pr_number — prints the open PR for $BRANCH, opening one if there is none.
pr_number() {
  local number url
  number="$(gh pr list --head "$BRANCH" --state open --json number --jq '.[0].number // empty')"
  if [[ -z "$number" ]]; then
    url="$(gh pr create --base main --head "$BRANCH" --title "$SUBJECT" \
      --body "Regenerated by the knowledge-bundle workflow. Auto-merges once the required checks pass.")"
    number="${url##*/}"
  fi
  printf '%s' "$number"
}

main() {
  require_env BRANCH SUBJECT GH_TOKEN
  [[ -f "$BUNDLE_PATH" ]] || { printf 'error: no bundle at %s\n' "$BUNDLE_PATH" >&2; exit 2; }

  commit_bundle
  push_branch

  local number
  number="$(pr_number)"
  gh pr merge "$number" --auto --squash --subject "$SUBJECT [skip ci]" --body ""
  printf 'PR #%s: auto-merge enabled.\n' "$number"
}

main "$@"
